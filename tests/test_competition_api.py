class TestLiveSafety:
    def test_no_competition_route_can_promote_or_arm(self):
        """No competition module may CALL a promotion or order-placing path.

        Parsed rather than grepped: both modules legitimately mention the operator path in prose
        ("promotion stays behind the GO LIVE arm phrase"), and a substring search would flag the
        docstring that documents the safety property it is checking.
        """
        import ast
        import inspect
        from app.competition import service as svc_mod
        from app.core import api_competition
        banned = {"promote", "demote", "live_arm", "arm_live", "place_order", "create_order",
                  "flatten_all", "set_live_strategies"}
        for mod in (api_competition, svc_mod):
            tree = ast.parse(inspect.getsource(mod))
            called = set()
            for node in ast.walk(tree):
                if isinstance(node, ast.Call):
                    fn = node.func
                    name = getattr(fn, "attr", None) or getattr(fn, "id", None)
                    if name:
                        called.add(name)
            assert not (called & banned), f"{mod.__name__} calls {sorted(called & banned)}"

    def test_service_holds_no_exchange_client(self, tmp_path):
        svc, _, _ = service(tmp_path)
        assert not hasattr(svc, "client")
        assert not hasattr(svc, "router")

    @pytest.mark.asyncio
    async def test_a_live_candidate_label_does_not_change_the_engine(self, tmp_path):
        svc, st, _ = service(tmp_path)
        await run_season(svc)
        # the competition writes only its own tables
        rows = st.conn.execute("SELECT COUNT(*) AS n FROM strategy_state").fetchone()
        assert rows["n"] == 0, "a season must not touch live strategy state"


