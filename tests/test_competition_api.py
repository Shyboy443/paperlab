class TestSeasonOwnsItsRiskConfig:
    """A Season's starting balance must be what the books actually start with.

    Regression: ReplayEngine sizes from `settings.strategy_starting_balance`, so a season built
    with RiskConfig(starting_balance=20) replayed at the server's env default (100) while the
    dashboard header truthfully quoted the season's 20. Caught in the GUI, not by the CLI, because
    the CLI builds its settings from the same --balance flag.
    """

    @pytest.mark.asyncio
    async def test_starting_balance_comes_from_the_season_not_the_environment(self, tmp_path):
        from app.competition.config import RiskConfig
        s = settings_factory(data_dir=str(tmp_path / "d"), SYMBOLS=SYMBOL, balance=100.0)
        st = seeded_storage(tmp_path)
        svc = CompetitionService(s, st, {"T01": OneShot}, rules=big_rules())
        assert s.strategy_starting_balance == 100.0
        d = svc.data_report([SYMBOL])
        season = svc.build_season(symbols=[SYMBOL], start_ms=d["overlap_start_ms"],
                                  end_ms=d["overlap_end_ms"], starting_balance=20.0)
        assert season.risk.starting_balance == 20.0
        rid = await svc.start(season, "realistic")
        await svc._task
        c = st.competition_competitor(rid, "T01")
        assert c["metrics"]["starting_equity"] == pytest.approx(20.0)

    @pytest.mark.asyncio
    async def test_risk_per_trade_also_follows_the_season(self, tmp_path):
        from app.competition.config import RiskConfig
        from app.competition.engine import CompetitionEngine
        s = settings_factory(data_dir=str(tmp_path / "d"), SYMBOLS=SYMBOL)
        st = seeded_storage(tmp_path)
        svc = CompetitionService(s, st, {"T01": OneShot}, rules=big_rules())
        d = svc.data_report([SYMBOL])
        season = svc.build_season(symbols=[SYMBOL], start_ms=d["overlap_start_ms"],
                                  end_ms=d["overlap_end_ms"], starting_balance=20.0)
        season = dataclasses.replace(season, risk=RiskConfig(starting_balance=20.0,
                                                            risk_per_trade_pct=0.01))
        eng = CompetitionEngine(s, season, rules=big_rules())
        assert eng._season_settings().risk_per_trade_pct == pytest.approx(0.01)
        assert eng._season_settings().strategy_starting_balance == pytest.approx(20.0)
