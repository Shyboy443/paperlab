class TestLeaderboard:
    @pytest.mark.asyncio
    async def test_rows_carry_the_real_metrics(self, tmp_path):
        svc, st, _ = service(tmp_path)
        await run_season(svc)
        comps = st.competition_competitors(svc.latest_run_id)
        t01 = next(c for c in comps if c["strategy_id"] == "T01")
        assert t01["metrics"]["trades"] >= 1
        assert set(mx.CompetitorMetrics("x").to_dict()) <= set(t01["metrics"])

    @pytest.mark.asyncio
    async def test_state_matches_judge(self, tmp_path):
        from app.competition.config import QualificationConfig
        from app.competition.qualification import judge
        svc, st, _ = service(tmp_path)
        await run_season(svc)
        for c in st.competition_competitors(svc.latest_run_id):
            if not c.get("metrics"):
                continue
            m = mx.CompetitorMetrics("x")
            for k, v in c["metrics"].items():
                setattr(m, k, v)
            assert c["state"] == judge(m, QualificationConfig()).state

    @pytest.mark.asyncio
    async def test_gross_and_net_match_the_metrics_engine(self, tmp_path):
        svc, st, _ = service(tmp_path)
        await run_season(svc)
        c = st.competition_competitor(svc.latest_run_id, "T01")
        m = c["metrics"]
        rebuilt = m["gross_pnl"] - m["fees_paid"] - m["slippage_cost"] + m["funding_paid"]
        assert m["net_profit"] == pytest.approx(rebuilt, abs=1e-9)
        assert m["latency_cost"] + m["spread_cost"] + m["impact_cost"] == \
            pytest.approx(m["slippage_cost"], abs=1e-9)

    @pytest.mark.asyncio
    async def test_rank_is_separate_from_qualification(self, tmp_path):
        """The product concept: #1 by score can still be INSUFFICIENT_SAMPLE."""
        svc, st, _ = service(tmp_path)
        await run_season(svc)
        comps = [c for c in st.competition_competitors(svc.latest_run_id) if c.get("metrics")]
        top = min(comps, key=lambda c: c["rank"])
        assert top["rank"] == 1
        assert top["state"] != "QUALIFIED", "a one-month season cannot qualify anything"


