def seeded_storage(tmp_path, n=60):
    """A storage with a real candle window, the way the live feed backfills it."""
    st = Storage(str(tmp_path / "t.db"))
    closes = [100.0 * (1.004 ** i) for i in range(n)]
    st.insert_candles(make_candles(closes=closes, symbol=SYMBOL, tf="1m", start_ts=T0, wick=0.0))
    return st


def service(tmp_path, n=60):
    s = settings_factory(data_dir=str(tmp_path / "data"), SYMBOLS=SYMBOL)
    st = seeded_storage(tmp_path, n)
    return CompetitionService(s, st, {"T01": OneShot, "T02": Idle}, rules=big_rules()), st, s


async def run_season(svc, profile="realistic", **over):
    data = svc.data_report([SYMBOL])
    season = svc.build_season(symbols=[SYMBOL], start_ms=data["overlap_start_ms"],
                              end_ms=data["overlap_end_ms"], profile=profile, **over)
    run_id = await svc.start(season, profile)
    await svc._task
    return run_id


